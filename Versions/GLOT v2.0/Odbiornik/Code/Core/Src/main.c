void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART2)
    {
        // Zapisujemy odebrany bajt do bufora
        crsf_buffer[crsf_index] = rx_byte;

        // Jeśli pierwszy bajt to nie jest magiczne 0xC8 (200), to ignorujemy śmieci
        if (crsf_index == 0 && crsf_buffer[0] != 0xC8) {
            crsf_index = 0;
        }
        else {
            crsf_index++;
        }

        // Ramka z kanałami RC w CRSF ma dokładnie 26 bajtów
        if (crsf_index >= 26) {
            // Sprawdzamy czy to ramka z pozycjami drążków (Typ ramki = 0x16)
            if (crsf_buffer[2] == 0x16) {

                // Magia przesunięć bitowych CRSF (rozpakowywanie 11-bitowych danych z 8-bitowych bajtów)
                // Kanał 1 (Roll)
                roll = (uint16_t)((crsf_buffer[3] | crsf_buffer[4] << 8) & 0x07FF);
                // Kanał 2 (Pitch)
                pitch = (uint16_t)((crsf_buffer[4] >> 3 | crsf_buffer[5] << 5) & 0x07FF);
                // Kanał 3 (Throttle)
                throttle = (uint16_t)((crsf_buffer[5] >> 6 | crsf_buffer[6] << 2 | crsf_buffer[7] << 10) & 0x07FF);
                // Kanał 4 (Yaw)
                yaw = (uint16_t)((crsf_buffer[7] >> 1 | crsf_buffer[8] << 7) & 0x07FF);

                // (Opcjonalnie) Kolejne kanały, np. na uzbrajanie silników (AUX1) byłyby dalej
            }
            crsf_index = 0; // Zaczynamy szukać kolejnej ramki od nowa
        }

        // ZNOWU UZBRAJAMY PRZERWANIE na kolejny bajt
        HAL_UART_Receive_IT(&huart2, &rx_byte, 1);
    }
}

